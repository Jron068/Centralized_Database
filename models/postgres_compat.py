"""Small compatibility layer for the app's existing DB-API calls on PostgreSQL."""

import re

import psycopg
from psycopg.rows import dict_row


def _split_sql_args(value):
    parts, start, depth, quote = [], 0, 0, None
    i = 0
    while i < len(value):
        char = value[i]
        if quote:
            if char == quote:
                if i + 1 < len(value) and value[i + 1] == quote:
                    i += 1
                else:
                    quote = None
        elif char in "'\"":
            quote = char
        elif char == "(":
            depth += 1
        elif char == ")":
            depth -= 1
        elif char == "," and depth == 0:
            parts.append(value[start:i].strip())
            start = i + 1
        i += 1
    parts.append(value[start:].strip())
    return parts


def _replace_function(sql, function, replacement):
    """Replace calls while respecting nested functions and quoted strings."""
    pattern = re.compile(rf"\b{function}\s*\(", re.IGNORECASE)
    while match := pattern.search(sql):
        start = match.end()
        depth, quote, end = 1, None, start
        while end < len(sql) and depth:
            char = sql[end]
            if quote:
                if char == quote:
                    if end + 1 < len(sql) and sql[end + 1] == quote:
                        end += 1
                    else:
                        quote = None
            elif char in "'\"":
                quote = char
            elif char == "(":
                depth += 1
            elif char == ")":
                depth -= 1
            end += 1
        if depth:
            break
        args = _split_sql_args(sql[start:end - 1])
        sql = sql[:match.start()] + replacement(args) + sql[end:]
    return sql


def _translate_create_table(sql):
    table_match = re.search(
        r"CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?`?([\w]+)`?",
        sql, re.IGNORECASE,
    )
    indexes = []
    if table_match:
        table_name = table_match.group(1)
        indexes = re.findall(
            r"(?:INDEX|KEY)\s+`?([\w]+)`?\s*\(([^)]+)\)", sql, re.IGNORECASE
        )
        sql = re.sub(
            r",?\s*(?:INDEX|KEY)\s+`?[\w]+`?\s*\([^)]+\)\s*,?",
            "",
            sql,
            flags=re.IGNORECASE,
        )
    sql = re.sub(
        r"\b([\w]+)\s+INT(?:\(\d+\))?\s+(?:NOT\s+NULL\s+)?AUTO_INCREMENT\b",
        r"\1 INTEGER GENERATED BY DEFAULT AS IDENTITY",
        sql,
        flags=re.IGNORECASE,
    )
    sql = re.sub(r"\bINT\(\d+\)\b", "INTEGER", sql, flags=re.IGNORECASE)
    sql = re.sub(r"\bTINYINT\(1\)\b", "SMALLINT", sql, flags=re.IGNORECASE)
    sql = re.sub(r"\bUNSIGNED\b", "", sql, flags=re.IGNORECASE)
    sql = re.sub(r"\bDATETIME\b", "TIMESTAMP", sql, flags=re.IGNORECASE)
    sql = re.sub(r"\bENUM\s*\([^)]*\)", "VARCHAR(50)", sql, flags=re.IGNORECASE)
    sql = re.sub(r"\s+ON\s+UPDATE\s+CURRENT_TIMESTAMP(?:\(\))?", "", sql, flags=re.IGNORECASE)
    sql = re.sub(r"\s+AUTO_INCREMENT\s*=\s*\d+", "", sql, flags=re.IGNORECASE)
    sql = re.sub(r"\s+ENGINE\s*=\s*\w+", "", sql, flags=re.IGNORECASE)
    sql = re.sub(r"\s+DEFAULT\s+CHARSET\s*=\s*\w+", "", sql, flags=re.IGNORECASE)
    sql = re.sub(r"\s+COLLATE\s*=\s*\w+", "", sql, flags=re.IGNORECASE)
    sql = sql.replace("`", "")
    return sql, table_name if table_match else None, indexes


def translate_mysql_sql(sql):
    """Translate the limited MySQL syntax used by this app to PostgreSQL."""
    statement = sql.strip()
    indexes = []
    table_name = None
    if re.match(r"CREATE\s+TABLE\b", statement, re.IGNORECASE):
        statement, table_name, indexes = _translate_create_table(statement)

    # The application inspects column metadata for a few optional database fields.
    if "information_schema.COLUMNS" in statement:
        statement = re.sub(r"\bDATABASE\(\)", "current_schema()", statement, flags=re.IGNORECASE)
        statement = re.sub(
            r"\bEXTRA\s+AS\s+extra",
            "CASE WHEN is_identity = 'YES' THEN 'auto_increment' ELSE '' END AS extra",
            statement,
            flags=re.IGNORECASE,
        )
        statement = re.sub(r"\bCOLUMN_TYPE\s+AS\s+t", "data_type AS t", statement, flags=re.IGNORECASE)
        statement = re.sub(r"information_schema\.COLUMNS", "information_schema.columns", statement, flags=re.IGNORECASE)

    statement = statement.replace("`", "")
    statement = re.sub(r"\bCURDATE\(\)", "CURRENT_DATE", statement, flags=re.IGNORECASE)
    statement = re.sub(r"\bNOW\(\)", "CURRENT_TIMESTAMP", statement, flags=re.IGNORECASE)
    statement = re.sub(
        r"INTERVAL\s+(\d+)\s+DAY\b", r"INTERVAL '\1 days'", statement, flags=re.IGNORECASE
    )
    statement = _replace_function(
        statement,
        "DATE_ADD",
        lambda args: f"({args[0]} + {args[1]})" if len(args) == 2 else f"DATE_ADD({', '.join(args)})",
    )
    statement = _replace_function(
        statement,
        "DATEDIFF",
        lambda args: f"(({args[0]})::date - ({args[1]})::date)"
        if len(args) == 2 else f"DATEDIFF({', '.join(args)} )",
    )
    statement = _replace_function(
        statement,
        "LOCATE",
        lambda args: f"STRPOS({args[1]}, {args[0]})"
        if len(args) == 2 else f"LOCATE({', '.join(args)})",
    )
    statement = _replace_function(
        statement,
        "DATE",
        lambda args: f"({args[0]})::date" if len(args) == 1 else f"DATE({', '.join(args)})",
    )

    def date_format(args):
        if len(args) != 2:
            return f"DATE_FORMAT({', '.join(args)})"
        fmt = args[1].strip().strip("'").replace("%%", "%")
        for mysql_fmt, pg_fmt in (("%Y", "YYYY"), ("%m", "MM"), ("%d", "DD")):
            fmt = fmt.replace(mysql_fmt, pg_fmt)
        if fmt == "YYYY-MM-01":
            return f"DATE_TRUNC('month', {args[0]})"
        return f"TO_CHAR({args[0]}, '{fmt}')"

    statement = _replace_function(statement, "DATE_FORMAT", date_format)
    statement = re.sub(
        r"GROUP_CONCAT\(\s*DISTINCT\s+([\w.]+)\s+ORDER\s+BY\s+([\w.]+)\s+SEPARATOR\s+'([^']*)'\s*\)",
        r"STRING_AGG(DISTINCT \1, '\3' ORDER BY \2)",
        statement,
        flags=re.IGNORECASE,
    )
    statement = re.sub(
        r"ON\s+DUPLICATE\s+KEY\s+UPDATE\s+profile_photo_path\s*=\s*VALUES\(profile_photo_path\)",
        "ON CONFLICT (account_id) DO UPDATE SET profile_photo_path = EXCLUDED.profile_photo_path, updated_at = CURRENT_TIMESTAMP",
        statement,
        flags=re.IGNORECASE,
    )
    statement = re.sub(r"'%%", "'%", statement)
    statement = re.sub(r"%%'", "%'", statement)
    return statement, table_name, indexes


class PostgresCursor:
    def __init__(self, connection, cursor):
        self._connection = connection
        self._cursor = cursor

    def execute(self, sql, params=None):
        statement, table_name, indexes = translate_mysql_sql(sql)
        self._cursor.execute(statement, params)
        if table_name:
            for name, columns in indexes:
                self._cursor.execute(
                    f"CREATE INDEX IF NOT EXISTS {name} ON {table_name} ({columns})"
                )
        return self

    def executemany(self, sql, params_seq):
        statement, _, _ = translate_mysql_sql(sql)
        self._cursor.executemany(statement, params_seq)
        return self

    @property
    def lastrowid(self):
        with self._connection._connection.cursor() as cursor:
            cursor.execute("SELECT LASTVAL()")
            return cursor.fetchone()[0]

    def __getattr__(self, name):
        return getattr(self._cursor, name)


class PostgresConnection:
    def __init__(self, connection):
        self._connection = connection

    def cursor(self, dictionary=False, **kwargs):
        if dictionary:
            kwargs["row_factory"] = dict_row
        return PostgresCursor(self, self._connection.cursor(**kwargs))

    def __getattr__(self, name):
        return getattr(self._connection, name)


def connect_postgres(database_url):
    return PostgresConnection(
        psycopg.connect(
            database_url,
            connect_timeout=10,
            sslmode="require",
            prepare_threshold=None,
        )
    )
